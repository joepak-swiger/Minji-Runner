import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..', '..');
const expoRoot = path.resolve(scriptDir, '..');
const outputFile = path.join(expoRoot, 'src', 'gameContent.js');

const MIME_TYPES = Object.freeze({
  '.png': 'image/png',
  '.gif': 'image/gif',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.mp3': 'audio/mpeg',
  '.wav': 'audio/wav',
  '.ogg': 'audio/ogg',
});

const assetMap = buildAssetMap(path.join(projectRoot, 'assets'));
const bundle = bundleModules('js/main.js');

let html = fs.readFileSync(path.join(projectRoot, 'index.html'), 'utf8');
let css = fs.readFileSync(path.join(projectRoot, 'styles.css'), 'utf8');
css = replaceAssetPaths(css);

html = html
  .replace('<html lang="en">', '<html lang="en" class="expo-host">')
  .replace(/\s*<link\s+rel="preload"[^>]*>\s*/g, '\n')
  .replace('<link rel="stylesheet" href="styles.css" />', `<style>\n${css}\n</style>`)
  .replace('<script type="module" src="js/main.js"></script>', `<script>\n${bundle}\n</script>`);

html = replaceAssetPaths(html);

const banner = `// AUTO-GENERATED by expo-mobile/tools/build-game-content.mjs\n// Do not hand-edit. Edit the canonical web game, then run: npm run mobile:sync\n`;
fs.writeFileSync(outputFile, `${banner}export const GAME_HTML = ${JSON.stringify(html)};\n`, 'utf8');

const bytes = fs.statSync(outputFile).size;
console.log(`Built Expo Go game payload: ${path.relative(projectRoot, outputFile)}`);
console.log(`Self-contained payload size: ${(bytes / 1024 / 1024).toFixed(2)} MiB`);

function buildAssetMap(assetRoot) {
  const map = new Map();
  for (const file of walk(assetRoot)) {
    const ext = path.extname(file).toLowerCase();
    const mime = MIME_TYPES[ext];
    if (!mime) continue;
    const rel = toPosix(path.relative(projectRoot, file));
    const encoded = fs.readFileSync(file).toString('base64');
    map.set(rel, `data:${mime};base64,${encoded}`);
  }
  return map;
}

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (entry.isFile()) yield full;
  }
}

function replaceAssetPaths(source) {
  let output = source;
  const entries = [...assetMap.entries()].sort((a, b) => b[0].length - a[0].length);
  for (const [assetPath, dataUri] of entries) {
    output = output.split(assetPath).join(dataUri);
  }
  return output;
}

function bundleModules(entryId) {
  const modules = new Map();
  collectModule(normalizeModuleId(entryId));

  const serialized = [...modules.entries()]
    .map(([id, body]) => `${JSON.stringify(id)}: function(module, exports, __require) {\n${indent(body, 4)}\n  }`)
    .join(',\n');

  return `(() => {\n  const __modules = {\n${indent(serialized, 4)}\n  };\n  const __cache = Object.create(null);\n  function __require(id) {\n    if (__cache[id]) return __cache[id].exports;\n    const factory = __modules[id];\n    if (!factory) throw new Error('Minji Runner mobile bundle missing module: ' + id);\n    const module = { exports: {} };\n    __cache[id] = module;\n    factory(module, module.exports, __require);\n    return module.exports;\n  }\n  __require(${JSON.stringify(normalizeModuleId(entryId))});\n})();`;

  function collectModule(id) {
    if (modules.has(id)) return;
    const filename = path.join(projectRoot, ...id.split('/'));
    let source = fs.readFileSync(filename, 'utf8');
    source = replaceAssetPaths(source);

    const imports = [];
    source = source.replace(
      /^\s*import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"]\s*;?/gm,
      (_match, clause, specifier) => {
        if (!specifier.startsWith('.')) {
          throw new Error(`External browser import is not supported in ${id}: ${specifier}`);
        }
        const dependencyId = resolveImport(id, specifier);
        collectModule(dependencyId);
        const replacement = importClauseToRequire(clause.trim(), dependencyId, imports.length);
        imports.push(dependencyId);
        return replacement;
      },
    );

    const namedExports = [];
    let defaultExport = null;

    source = source.replace(/^\s*export\s+default\s+class\s+([A-Za-z_$][\w$]*)/gm, (_m, name) => {
      defaultExport = name;
      return `class ${name}`;
    });

    source = source.replace(/^\s*export\s+default\s+function\s+([A-Za-z_$][\w$]*)/gm, (_m, name) => {
      defaultExport = name;
      return `function ${name}`;
    });

    source = source.replace(/^\s*export\s+const\s+([A-Za-z_$][\w$]*)/gm, (_m, name) => {
      namedExports.push(name);
      return `const ${name}`;
    });

    source = source.replace(/^\s*export\s+function\s+([A-Za-z_$][\w$]*)/gm, (_m, name) => {
      namedExports.push(name);
      return `function ${name}`;
    });

    if (/^\s*export\s+/m.test(source)) {
      throw new Error(`Unsupported export syntax remains in ${id}`);
    }

    const exportLines = [
      ...new Set(namedExports).values(),
    ].map((name) => `exports.${name} = ${name};`);
    if (defaultExport) exportLines.push(`exports.default = ${defaultExport};`);

    const body = `${source.trim()}\n${exportLines.join('\n')}`;
    modules.set(id, body);
  }
}

function importClauseToRequire(clause, dependencyId, index) {
  const dep = `__dep${index}`;
  const req = `__require(${JSON.stringify(dependencyId)})`;

  if (clause.startsWith('{')) {
    return `const ${normalizeNamedImports(clause)} = ${req};`;
  }

  if (clause.startsWith('* as ')) {
    const name = clause.slice(5).trim();
    return `const ${name} = ${req};`;
  }

  const comma = clause.indexOf(',');
  if (comma === -1) {
    return `const { default: ${clause.trim()} } = ${req};`;
  }

  const defaultName = clause.slice(0, comma).trim();
  const rest = clause.slice(comma + 1).trim();
  const lines = [`const ${dep} = ${req};`, `const ${defaultName} = ${dep}.default;`];
  if (rest.startsWith('{')) lines.push(`const ${normalizeNamedImports(rest)} = ${dep};`);
  else if (rest.startsWith('* as ')) lines.push(`const ${rest.slice(5).trim()} = ${dep};`);
  else throw new Error(`Unsupported import clause: ${clause}`);
  return lines.join('\n');
}

function normalizeNamedImports(clause) {
  const inner = clause.trim().replace(/^\{/, '').replace(/\}$/, '').trim();
  if (!inner) return '{}';
  const converted = inner
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
    .map((part) => part.replace(/\s+as\s+/g, ': '))
    .join(', ');
  return `{ ${converted} }`;
}

function resolveImport(fromId, specifier) {
  const dir = path.posix.dirname(fromId);
  let resolved = path.posix.normalize(path.posix.join(dir, specifier));
  if (!path.posix.extname(resolved)) resolved += '.js';
  return normalizeModuleId(resolved);
}

function normalizeModuleId(id) {
  return toPosix(path.posix.normalize(id)).replace(/^\.\//, '');
}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function indent(text, spaces) {
  const prefix = ' '.repeat(spaces);
  return text.split('\n').map((line) => `${prefix}${line}`).join('\n');
}
